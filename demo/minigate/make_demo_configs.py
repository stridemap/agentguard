#!/usr/bin/env python3
"""Regenerate the per-scenario config variants from minigate.yaml.

Scenarios 3, 5 and 10 each need a small edit to the live config. Keeping them as
hand-copied files means they silently demo yesterday's policy the moment minigate.yaml
changes — which is exactly what happened when the active policy was swapped. Derive them
instead, and re-run this after every config change.

    python3 demo/minigate/make_demo_configs.py

The variants are written beside minigate.yaml on purpose: MiniGate resolves relative paths
in a config against that config's own directory, so a copy placed anywhere else fails with
a missing policy file.

Each variant is a *textual* edit rather than a YAML round-trip, so the comments — which
carry most of the reasoning in that file — survive into the demo artefacts.
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "minigate.yaml"

GREEN, RED, DIM, RESET = "\033[32m", "\033[31m", "\033[2m", "\033[0m"

# Scenario 5 needs trust levels that make one Linear tool a source and another a sink.
# Anchored on the shipped comment so a missing anchor is an error, not a silent no-op.
TOOL_TRUST_ANCHOR = "      create_public_issue: public"
TOOL_TRUST = TOOL_TRUST_ANCHOR + """
      get_issue: confidential
      list_issues: confidential
      save_comment: public
      save_document: public"""

# Scenario 10 needs a url-backed server. A server has one upstream: a command or a url.
REMOTE_ANCHOR = "  linear:\n"
REMOTE = """  linear-remote:
    url: https://mcp.linear.app/mcp
    authorization_servers: ["https://mcp.linear.app"]
    trust: internal

  linear:
"""

VARIANTS = {
    "minigate-s3.yaml": [
        ("  path: minigate-registry.yaml",
         "  path: demo/minigate/evidence/minigate-registry.pre-sync.yaml"),
    ],
    "minigate-s5.yaml": [
        ("lineage:\n  enabled: false", "lineage:\n  enabled: true"),
        ("  mode: observe             # off | observe | enforce",
         "  mode: enforce             # off | observe | enforce"),
        (TOOL_TRUST_ANCHOR, TOOL_TRUST),
    ],
    "minigate-s10.yaml": [
        (REMOTE_ANCHOR, REMOTE),
    ],
}

BANNER = ("# GENERATED by demo/minigate/make_demo_configs.py — do not edit.\n"
          "# Re-run that script after any change to minigate.yaml.\n")


def main() -> int:
    if not SOURCE.exists():
        print(f"{RED}{SOURCE} not found{RESET}")
        return 1
    source = SOURCE.read_text()

    active = next((ln for ln in source.splitlines()
                   if ln.startswith("policy:")), "policy: (unset)")
    print(f"\nfrom {SOURCE.name}  {DIM}{active}{RESET}\n")

    for name, edits in VARIANTS.items():
        text = source
        for find, replace in edits:
            if text.count(find) != 1:
                print(f"  {RED}{name}: anchor appears {text.count(find)}x, expected 1{RESET}")
                print(f"    {DIM}{find.splitlines()[0]}{RESET}")
                return 1
            text = text.replace(find, replace)
        (REPO / name).write_text(BANNER + text)
        print(f"  {GREEN}wrote{RESET}  {name}")

    print(f"\n{DIM}  Variants inherit whatever policy minigate.yaml points at, so they{RESET}")
    print(f"{DIM}  track it automatically from now on.{RESET}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
